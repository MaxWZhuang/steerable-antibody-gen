def write(path, document):
    path.write_bytes(canonical_bytes(document))
    return path


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


@pytest.fixture(autouse=True)
def single_thread():
    previous = torch.get_num_threads()
    torch.set_num_threads(1)
    try:
        yield
    finally:
        torch.set_num_threads(previous)


def run(*args):
    cli.main([str(arg) for arg in args])


def mid_config(tmp_path, *, updates=3):
    broad = _broad_document()
    broad["records"][0]["Ag"] = "WVW"  # Distinct from the held-out target.
    write(tmp_path / "pairs.json", broad)
    write(tmp_path / "endpoints.json", _endpoint_document())
    config = {
        "schema": "trastuzumab-run/2", "model": {"kind": "tiny"}, "functional": None,
        "fusion": {"context_dim": 8, "bottleneck": 6, "lora_rank": 2, "lora_alpha": 4,
                   "lora_dropout": 0.1, "activation_checkpointing": False},
        "training": {"stage": "mid", "arm": "paired", "seed": 17, "total_updates": updates,
                     "examples_per_update": 2, "learning_rate": 0.002, "schedule": "cosine"},
        "data": {"pairs_path": "pairs.json", "transfer_guard": {
            "endpoint_manifest_path": "endpoints.json", "excluded_antibody_families": ["heldout-ab"],
            "excluded_target_families": ["heldout-target"]}},
        "initialization": {"kind": "release"}, "device": "cpu",
    }
    return write(tmp_path / "config.json", config), config


def assert_export(directory, filename):
    manifest = read_json(directory / "manifest.json")
    assert manifest["schema"] == "trastuzumab-export/1"
    assert set(manifest["files"]) == {filename, "metadata.json"}
    for name, binding in manifest["files"].items():
        data = (directory / name).read_bytes()
        assert binding == {"sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data)}
    return read_json(directory / filename), read_json(directory / "metadata.json")


def test_actual_cli_train_resume_exports_and_fresh_post_from_parent(tmp_path, monkeypatch):
    config_path, config = mid_config(tmp_path)
    outside = tmp_path / "outside"
    outside.mkdir()
    monkeypatch.chdir(outside)  # Data paths belong to config location, not process cwd.
    coverage_path = tmp_path / "coverage.json"
    run("qualify", "--pairs", tmp_path / "pairs.json", "--output", coverage_path)
    coverage = read_json(coverage_path)
    assert coverage["coverage"]["input_rows"] == coverage["coverage"]["unique_pairs"] == 1

    partial_dir, resumed_dir, full_dir = [tmp_path / name for name in ("partial", "resumed", "full")]
    run("train", "--config", config_path, "--output", partial_dir,
        "--stop-after-updates", 1, "--checkpoint-every", 1)
    partial = read_json(partial_dir / "result.json")
    assert partial["status"] == "stopped_at_boundary"
    assert partial["progress"]["next_update"] == 1
    assert partial["checkpoint"]["sha256"] == sha(partial_dir / "checkpoint.pt")
    run("train", "--config", config_path, "--output", resumed_dir,
        "--resume", partial_dir / "checkpoint.pt", "--resume-sha256", partial["checkpoint"]["sha256"])
    run("train", "--config", config_path, "--output", full_dir)
    resumed = read_json(resumed_dir / "result.json")
    uninterrupted = read_json(full_dir / "result.json")
    assert resumed["status"] == uninterrupted["status"] == "complete"
    assert resumed["progress"] == uninterrupted["progress"]
    assert resumed["progress"]["counters"]["examples"] == 6
    logs = [json.loads(line) for line in (resumed_dir / "metrics.jsonl").read_text().splitlines()]
    assert [row["update"] for row in logs] == [2, 3]
    # These are only checkpoints generated by the tiny test above.
    a = torch.load(resumed_dir / "checkpoint.pt", weights_only=True)
    b = torch.load(full_dir / "checkpoint.pt", weights_only=True)
    assert a["identity"] == b["identity"]
    assert set(a["weights"]) == set(b["weights"])
    assert all(torch.equal(a["weights"][key], b["weights"][key]) for key in a["weights"])

    checkpoint_path = resumed_dir / "checkpoint.pt"
    checkpoint_hash = resumed["checkpoint"]["sha256"]
    queries = write(tmp_path / "queries.json", _panel_document())
    (tmp_path / "pairs.json").unlink()  # Inference/export must never reopen fitting inputs.
    common = ("--config", config_path, "--checkpoint", checkpoint_path, "--checkpoint-sha256", checkpoint_hash)
    score_dir = tmp_path / "scores"
    run("score", *common, "--queries", queries, "--arm", "paired", "--scorer-id", "tiny-trained",
        "--orders", 1, "--order-seed", 23, "--output", score_dir)
    table, metadata = assert_export(score_dir, "scores.json")
    assert table["schema"] == "her2-benchmark/1" and table["record_kind"] == "score_table"
    assert table["orientation"] == "higher_is_better"
    assert {row["case_id"] for row in table["scores"]} == {"case-0", "case-1", "case-2"}
    assert all(row["failure"] is None for row in table["scores"])
    assert table["scores"][0]["score"] == table["scores"][2]["score"]
    assert table["provenance"]["metadata"] == digest(metadata)
    assert metadata["checkpoint"]["checkpoint_sha256"] == checkpoint_hash

    gen_dir = tmp_path / "generation"
    run("generate", *common, "--queries", queries, "--arm", "paired", "--arm-id", "tiny-trained-edit2",
        "--seeds", 7, 3, "--attempts-per-seed", 2, "--reference-core", "ACDEFGHIKL",
        "--editable-count", 2, "--steps", 2, "--output", gen_dir)
    attempts, generation_meta = assert_export(gen_dir, "attempts.json")
    assert attempts["budgets"] == {"tiny-trained-edit2": {"3": 2, "7": 2}}
    assert [(row["seed"], row["index"]) for row in attempts["attempts"]] == [(3, 0), (3, 1), (7, 0), (7, 1)]
    assert attempts["attempt_set_sha256"] == digest({k: v for k, v in attempts.items() if k != "attempt_set_sha256"})
    for row in attempts["attempts"]:
        assert row["failure_reason"] is None and len(row["raw_core"]) == 10
        assert row["source"]["hamming_distance"] <= 2
        assert row["source"]["metadata_sha256"] == digest(generation_meta)

    parent_path = tmp_path / "parent.pt"
    run("export-parent", *common, "--output", parent_path)
    endpoints = write(tmp_path / "endpoints.json", _endpoint_document())
    selected_path = tmp_path / "budget.json"
    run("select-budget", "--manifest", endpoints, "--budget", 2, "--budget-seed", "shared", "--output", selected_path)
    selected = read_json(selected_path)
    write(tmp_path / "labels.json", {
        "schema": "trastuzumab-selected-labels/1", "selection_digest": selected["selection_digest"],
        "measurements": [dict(endpoint_id=eid, value=float(i), orientation="higher_better", assay_id="SPR")
                         for i, eid in enumerate(selected["selected_ids"])],
    })
    post = deepcopy(config)
    post["training"] = dict(stage="post", arm="paired", seed=19, total_updates=1, examples_per_update=1,
                            learning_rate=0.001, ordering_weight=1.0)
    post["initialization"] = dict(kind="parent", path="parent.pt", sha256=sha(parent_path))
    post["data"] = dict(endpoint_manifest_path="endpoints.json", selected_labels_path="labels.json",
                        budget_n=2, budget_seed="shared")
    post_path = write(tmp_path / "post.json", post)
    post_dir = tmp_path / "post"
    run("train", "--config", post_path, "--output", post_dir)
    outcome = read_json(post_dir / "result.json")
    identity = read_json(post_dir / "identity.json")
    assert outcome["status"] == "complete" and outcome["progress"]["next_update"] == 1
    assert outcome["progress"]["fitting_endpoints_available"] == 2
    assert outcome["progress"]["selection_labels"] == 0
    assert outcome["progress"]["counters"]["teacher_forced_states"] == 20
    assert set(outcome["progress"]["seen"]["endpoints"]) == set(selected["selected_ids"])
    assert identity["initialization"]["kind"] == "parent"
    assert identity["initialization"]["sha256"] == sha(parent_path)
    assert outcome["progress"]["inherited_exposure"]["parent_progress"]["next_update"] == 3
    assert outcome["progress"]["inherited_exposure"]["external_declaration"] is None


def test_cli_cpu_profile_uses_actual_updates_and_never_forecasts_gpu(tmp_path):
    config_path, _ = mid_config(tmp_path)
    output = tmp_path / "profile.json"
    run("profile", "--config", config_path, "--output", output,
        "--warmup-updates", 1, "--measured-updates", 2)
    profile = read_json(output)
    assert profile["status"] == "software_smoke_only"
    assert profile["runtime"]["hardware"]["cuda"] is False
    assert profile["extrapolation"]["hours_per_million_training_units"] is None
    assert profile["training_units"] == 4
    assert [metric["update"] for metric in profile["metrics"]] == [2, 3]
    assert profile["execution"]["encoder"]["forward_starts"] == 4
    assert profile["execution"]["dplm"]["forward_starts"] == 4
    assert profile["seconds"] > 0 and profile["training_units_per_second"] > 0


def test_real_script_entrypoint_qualifies_explicit_synthetic_json(tmp_path):
    source = write(tmp_path / "pairs.json", _broad_document())
    output = tmp_path / "coverage.json"
    script = Path(__file__).resolve().parents[3] / "scripts" / "trastuzumab_train.py"
    result = subprocess.run([sys.executable, "-B", str(script), "qualify", "--pairs", str(source), "--output", str(output)],
                            cwd=tmp_path, capture_output=True, text=True, timeout=45)
    assert result.returncode == 0, result.stderr
    assert read_json(output)["coverage"]["unique_pairs"] == 1


@pytest.mark.parametrize("problem", ("score_orders", "query_outcome", "generation_seeds", "generation_strategy"))
def test_invalid_export_cli_preflights_before_constructing_models(tmp_path, monkeypatch, problem):
    config_path, _ = mid_config(tmp_path)
    document = _panel_document()
    if problem == "query_outcome":
        document["queries"][0]["pKD"] = 1.0
    queries = write(tmp_path / "queries.json", document)
    common = ["--config", config_path, "--output", tmp_path / "invalid-output", "--queries", queries,
              "--checkpoint", tmp_path / "not-opened.pt", "--checkpoint-sha256", "a" * 64, "--arm", "paired"]
    if problem.startswith("generation"):
        args = ["generate", *common, "--arm-id", "arm", "--seeds", 1, 1 if problem == "generation_seeds" else 2,
                "--attempts-per-seed", 1, "--reference-core", "ACDEFGHIKL"]
        if problem == "generation_strategy":
            args += ["--strategy", "reparam-uncond-stochastic1..2-linear"]
    else:
        args = ["score", *common, "--scorer-id", "score", "--orders", 0 if problem == "score_orders" else 1]

    def forbidden(*args, **kwargs):
        raise AssertionError("invalid export request constructed models")

    monkeypatch.setattr(cli, "models", forbidden)
    with pytest.raises(ValueError):
        run(*args)
    assert not (tmp_path / "invalid-output").exists()


def test_existing_cli_output_is_refused_without_reading_config_or_building_models(tmp_path, monkeypatch):
    destination = tmp_path / "existing"
    destination.mkdir()
    marker = destination / "keep.txt"
    marker.write_text("unchanged", encoding="utf-8")
    run_args = ("train", "--config", tmp_path / "missing.json", "--output", destination)
    with pytest.raises(ValueError, match="output already exists"):
        run(*run_args)
    assert marker.read_text(encoding="utf-8") == "unchanged"


def test_mid_plan_binds_holdout_without_models_and_rejects_overlap(tmp_path, monkeypatch):
    path, config = mid_config(tmp_path)
    monkeypatch.setattr(cli, "models", lambda *a: pytest.fail("planning constructed models"))
    output = tmp_path / "plan.json"
    run("plan", "--config", path, "--output", output)
    plan = read_json(output)
    assert plan["transfer_certificate"]["endpoint_manifest_digest"]
    assert plan["coverage"]["sampling"]["algorithm"] == "family_first_v1"
    broad = read_json(tmp_path / "pairs.json")
    broad["records"][0]["Ag"] = "HIK"
    write(tmp_path / "pairs.json", broad)
    with pytest.raises(ValueError, match="downstream antigen"):
        run("train", "--config", path, "--output", tmp_path / "rejected")
    assert not (tmp_path / "rejected").exists()


def test_post_plan_and_coverage_gate_precede_labels_and_models(tmp_path, monkeypatch):
    path, config = mid_config(tmp_path)
    endpoints = _endpoint_document()
    endpoints["entries"][2]["role"] = "post_pool"
    write(tmp_path / "endpoints.json", endpoints)
    config["training"] = dict(stage="post", total_updates=1, examples_per_update=1, ordering_weight=1.0)
    config["data"] = dict(endpoint_manifest_path="endpoints.json", selected_labels_path="MISSING_LABELS.json",
                          budget_n=3, budget_seed="shared")
    write(path, config)
    monkeypatch.setattr(cli, "models", lambda *a: pytest.fail("planning constructed models"))
    output = tmp_path / "plan.json"
    run("plan", "--config", path, "--output", output)
    plan = read_json(output)
    assert not plan["coverage_requirement_met"]
    assert plan["exposure"]["pair_labels"]["seen_endpoint_count"] == 2
    with pytest.raises(ValueError, match="declared horizon compares only"):
        run("train", "--config", path, "--output", tmp_path / "rejected")
    assert not (tmp_path / "rejected").exists()


