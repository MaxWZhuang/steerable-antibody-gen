#: The error asymmetry, declared before any measurement. A false MERGE is the
#: more expensive error: it destroys target diversity, corrupts every per-target
#: number computed downstream, and is invisible to a leakage audit because a
#: merged pair never straddles anything. A false SPLIT costs leakage, which a
#: leakage audit does detect and report. The operating point is therefore chosen
#: to tolerate more false splits than false merges. This string is carried on
#: every `ErrorReport` so it cannot be chosen after the numbers are known, and it
#: is byte-identical to the one predeclared in the acceptance fixtures.
