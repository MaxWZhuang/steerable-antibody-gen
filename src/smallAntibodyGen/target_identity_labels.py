"""
Hand-written ground truth for the target-identity audit population.

WHAT THESE ARE FOR
------------------
An operating point chosen on a population and then validated on that same
population reports its own selection back as an achieved error rate. So the
thresholds in `target_identity.OperatingPoint` are chosen against a synthetic
population generated by `entity_resolution.synthetic` -- which shares no code
with the resolver and plants its own truth -- and audited here, on real families
the selection never saw.

The split is by FAMILY and not by pair, so that a family cannot contribute a pair
to threshold selection and another pair to the confirmation of that selection.
All five real families below are reserved for the audit side; nothing here is
ever used for calibration.

WHY EACH RECORD IS LABELLED THE WAY IT IS
-----------------------------------------
``family`` is the leave-one-family-out unit. ``target`` is the claim being
scored: two records share a ``target`` exactly when a correct resolver MUST place
them in one biological family, and share only a ``family`` when they are related
and must stay apart. The four SARS-CoV-2 spike constructs are one family and
four different targets, which is what makes them a test rather than a formality.

The digests are the first 32 hex characters of the SHA-256 of the cleaned antigen
sequence, and every one of them is reproduced from the sequences committed in
`tests/fixtures_target_identity.py` by
`test_target_identity_engine.py::test_curated_labels_match_the_committed_fixtures`.
A label whose digest drifted away from its sequence would silently score a
different record than the one it describes.
"""
